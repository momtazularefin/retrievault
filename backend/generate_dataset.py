"""Propose evaluation questions from indexed chunks, for a human to curate.

    python generate_dataset.py [--per-chunk 2] [--chunks 25] [--seed 0]

Output goes to ``eval/dataset.candidates.jsonl``; it never overwrites ``eval/dataset.jsonl``.
Candidates are a draft: the model writes them from one chunk, so every question, reference
answer, gold file, and category must be checked against the pinned source before it joins the
evaluation set. The v1.0 set was generated by an earlier version of this script that read a
payload key that does not exist, so its questions were written without ever seeing the code.
"""

import argparse
import json
import random
import uuid
from pathlib import Path

from anthropic import Anthropic
from qdrant_client import QdrantClient

from retrievault.collection import MANIFEST_POINT_ID
from retrievault.config import get_settings

CANDIDATES_PATH = Path(__file__).parent / "eval" / "dataset.candidates.jsonl"
CATEGORIES = ("factual", "location", "how-it-works")

UNANSWERABLE = [
    "How do I deploy FastAPI on AWS Lambda using Zappa?",
    "What is the best way to integrate Django ORM with FastAPI?",
    "Does FastAPI support Flask blueprints?",
    "How to configure Celery broker in FastAPI core?",
    "What is the weather in Tokyo?",
]
REFUSAL_REFERENCE = (
    "The retrieved FastAPI source does not contain this information, so the question cannot be "
    "answered from the codebase."
)

PROMPT = """Here is one chunk of the FastAPI source code.

File: {file_path}
Symbol: {symbol_name} ({symbol_type}), lines {start_line}-{end_line}
```python
{code}
```

Write {count} questions that this chunk alone answers completely, with an answer grounded only
in the code above. Return raw JSON: a list of objects with the keys "question", \
"reference_answer", and "category", where category is one of {categories}.
Do not use knowledge of FastAPI beyond this chunk."""


def sample_chunks(client: QdrantClient, collection: str, count: int, seed: int) -> list[dict]:
    records, offset = [], None
    while True:
        batch, offset = client.scroll(collection, limit=256, offset=offset, with_payload=True)
        records.extend(r for r in batch if str(r.id) != MANIFEST_POINT_ID)
        if offset is None:
            break
    random.Random(seed).shuffle(records)
    return [r.payload for r in records[:count]]


def propose(anthropic: Anthropic, model: str, payload: dict, count: int) -> list[dict]:
    response = anthropic.messages.create(
        model=model,
        max_tokens=1500,
        system="You are an expert Python developer. Output raw JSON only.",
        messages=[
            {
                "role": "user",
                "content": PROMPT.format(
                    count=count, categories=list(CATEGORIES), **{k: payload.get(k, "") for k in
                    ("file_path", "symbol_name", "symbol_type", "start_line", "end_line", "code")}
                ),
            }
        ],
    )
    text = response.content[0].text
    start, end = text.find("["), text.rfind("]") + 1
    if start < 0 or end <= start:
        return []
    return json.loads(text[start:end])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--chunks", type=int, default=25)
    parser.add_argument("--per-chunk", type=int, default=2)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    settings = get_settings()
    client = QdrantClient(url=settings.qdrant_url, api_key=settings.qdrant_api_key_or_none)
    anthropic = Anthropic(api_key=settings.anthropic_api_key)

    candidates = [
        {
            "id": str(uuid.uuid4()),
            "question": question,
            "reference_answer": REFUSAL_REFERENCE,
            "gold_files": [],
            "gold_symbols": [],
            "category": "refusal",
        }
        for question in UNANSWERABLE
    ]

    for payload in sample_chunks(client, settings.qdrant_collection, args.chunks, args.seed):
        try:
            proposals = propose(
                anthropic, settings.retrievault_synthesis_model, payload, args.per_chunk
            )
        except (ValueError, KeyError, IndexError) as error:
            print(f"Skipped {payload.get('file_path')}: {error}")
            continue
        for proposal in proposals:
            category = proposal.get("category")
            candidates.append(
                {
                    "id": str(uuid.uuid4()),
                    "question": proposal["question"],
                    "reference_answer": proposal["reference_answer"],
                    "gold_files": [payload["file_path"]],
                    "gold_symbols": [payload["symbol_name"]],
                    "category": category if category in CATEGORIES else "factual",
                }
            )

    header = {
        "corpus_repo": settings.corpus_repo,
        "corpus_tag": settings.corpus_tag,
        "dataset_version": "candidates",
        "status": "UNCURATED - verify every item against the pinned source before use",
    }
    CANDIDATES_PATH.parent.mkdir(parents=True, exist_ok=True)
    with CANDIDATES_PATH.open("w", encoding="utf-8") as out:
        for row in [header, *candidates]:
            out.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"Wrote {len(candidates)} candidates to {CANDIDATES_PATH} (curation required)")


if __name__ == "__main__":
    main()
